/** Map known hotel filter ids to localized labels. Ambiguous numeric ids need a group hint. */
export function shopFilterOptionLabel(
  locale: ShopLocale,
  id: string,
  fallback: string,
  group?: "star" | "distance" | "review" | "meal" | "property" | "facility",
): string {
  if (group === "star") {
    const key = ({ "2": "star2", "3": "star3", "4": "star4", "5": "star5" } as Record<
      string,
      ShopUiKey
    >)[id];
    if (key) return tShop(locale, key);
  }
  if (group === "distance") {
    const key = ({ "1": "dist1", "3": "dist3", "5": "dist5" } as Record<string, ShopUiKey>)[id];
    if (key) return tShop(locale, key);
  }
  if (group === "review") {
    const key = ({ "9": "score9", "8": "score8", "7": "score7", "6": "score6" } as Record<
      string,
      ShopUiKey
    >)[id];
    if (key) return tShop(locale, key);
  }
  const key = FILTER_ID_KEYS[id];
  if (key && !group) return tShop(locale, key);
  if (key && (group === "meal" || group === "property" || group === "facility")) {
    return tShop(locale, key);
  }
  return fallback;
}
