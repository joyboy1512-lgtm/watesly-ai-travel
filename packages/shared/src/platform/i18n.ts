export type ShopUiKey = keyof (typeof SHOP_UI)["ar"];

export function tShop(locale: ShopLocale, key: ShopUiKey, vars?: ShopUiVars): string {
  let text = String(SHOP_UI[locale][key] ?? SHOP_UI.ar[key] ?? key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

